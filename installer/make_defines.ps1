# Generates download_defines.iss for blankslate.iss (slice names/SHA-256/sizes + per-group file stats).
# Two-pass build: run AFTER ISCC (it hashes the .bin slices), then recompile so the exe embeds fresh values.
param(
  [string]$BaseUrl = 'https://github.com/archanagaur175-glitch/BlankSlate-V2/releases/download/v2.0.0',
  [string]$OutputDir = 'C:\Users\archa\Documents\BlankSlate_V2\installer\output',
  [string]$DefinesFile = 'C:\Users\archa\Documents\BlankSlate_V2\installer\download_defines.iss',
  [string[]]$G1 = @('C:\Users\archa\Documents\BlankSlate_V2\hud\src-tauri\target\release\blankslate-hud.exe'),
  [string[]]$G2 = @('C:\Users\archa\Documents\BlankSlate_V2\daemon\dist\blankslate-daemon'),
  [string[]]$G3 = @("$env:LOCALAPPDATA\Programs\Ollama\ollama.exe", "$env:LOCALAPPDATA\Programs\Ollama\ollama app.exe", "$env:LOCALAPPDATA\Programs\Ollama\app.ico", "$env:LOCALAPPDATA\Programs\Ollama\lib"),
  [string[]]$G4 = @('C:\Users\archa\Documents\BlankSlate_V2\installer\assets\THIRD_PARTY_NOTICES.txt', 'C:\Users\archa\Documents\BlankSlate_V2\installer\assets\MicrosoftEdgeWebview2Setup.exe'),
  [string[]]$G5 = @('C:\Users\archa\Documents\BlankSlate_V2\installer\staging\seed_ollama_models', 'C:\Users\archa\Documents\BlankSlate_V2\installer\staging\seed_hf_hub')
)
$ErrorActionPreference = 'Stop'

function Get-Stats([string[]]$paths) {
  $files = 0
  [long]$bytes = 0
  foreach ($p in $paths) {
    if (-not (Test-Path -LiteralPath $p)) { throw "missing source: $p" }
    if (Test-Path -LiteralPath $p -PathType Container) {
      Get-ChildItem -LiteralPath $p -Recurse -File | ForEach-Object { $files++; $bytes += $_.Length }
    } else {
      $files++
      $bytes += (Get-Item -LiteralPath $p).Length
    }
  }
  [pscustomobject]@{ Files = $files; Bytes = $bytes }
}

$bins = @(Get-ChildItem -LiteralPath $OutputDir -Filter '*.bin' | Sort-Object { [int]($_.BaseName -replace '.*-', '') })
if ($bins.Count -lt 1) { throw "no .bin slices found in $OutputDir" }
if ($bins.Count -gt 9) { throw "more than 9 slices - update blankslate.iss SliceName/SliceBytes" }

$lines = @()
$lines += '; generated by make_defines.ps1 - do not edit by hand'
$lines += '#define DL_BASE "' + $BaseUrl + '"'
$lines += '#define BIN_COUNT ' + $bins.Count
$i = 0
foreach ($b in $bins) {
  $i++
  $sha = (Get-FileHash -LiteralPath $b.FullName -Algorithm SHA256).Hash.ToLower()
  $lines += "#define BIN${i}_NAME `"$($b.Name)`""
  $lines += "#define BIN${i}_SHA `"$sha`""
  $lines += "#define BIN${i}_BYTES $($b.Length)"
}

$gNames = @('G1', 'G2', 'G3', 'G4', 'G5')
$gPaths = @($G1, $G2, $G3, $G4, $G5)
$totFiles = 0
$totMB = 0
for ($g = 0; $g -lt 5; $g++) {
  $s = Get-Stats $gPaths[$g]
  $mb = [math]::Ceiling($s.Bytes / 1MB)
  $lines += "#define $($gNames[$g])_FILES $($s.Files)"
  $lines += "#define $($gNames[$g])_MB $mb"
  $totFiles += $s.Files
  $totMB += $mb
}
$lines += '#define TOT_FILES ' + $totFiles
$lines += '#define TOT_MB ' + $totMB

Set-Content -LiteralPath $DefinesFile -Value ($lines -join "`r`n") -Encoding UTF8
Write-Host "wrote $DefinesFile ($($bins.Count) slices, $totFiles files, $totMB MB)"
